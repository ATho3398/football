// 주요 국적(weight 4 이상 + 아르헨티나): 성 120개·이름 60개 이상, 나머지: 성 40개·이름 25개 이상.
// 한글은 한국 통용 표기 (C.44a: van → 반, van der → 반 데르, de → 더). 'Roman=한글' 을 쉼표로 잇는다

function pairs(s: string): [string, string][] {
  return s.split(',').map((e) => e.trim()).filter(Boolean).map((e) => {
    const [r, k] = e.split('=');
    return [r!.trim(), k!.trim()];
  });
}

